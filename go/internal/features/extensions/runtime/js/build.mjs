// Bundles the embedded extension runtime into
// go/internal/features/extensions/runtime/RaycastRuntime.generated.js.
//
// The output is committed: building Wincast never needs Node. Source lives
// here; run `npm install && npm run build` after changing it.

import { build } from "esbuild";
import { mkdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";

const outFile = resolve("..", "RaycastRuntime.generated.js");
const dev = process.argv.includes("--dev");

mkdirSync(dirname(outFile), { recursive: true });

const result = await build({
  entryPoints: ["src/entry.ts"],
  bundle: true,
  format: "iife",
  platform: "browser",
  target: ["es2022"],
  minify: !dev,
  sourcemap: false,
  legalComments: "none",
  write: false,
  define: {
    "process.env.NODE_ENV": dev ? '"development"' : '"production"',
    __DEV__: dev ? "true" : "false",
  },
  alias: {
    "@blastlauncher/protocol": resolve("src/blast/protocol/index.ts"),
    "node:fs": resolve("src/shims/node-fs.ts"),
    "node:path": resolve("src/shims/node-path.ts"),
    "node:crypto": resolve("src/shims/node-crypto.ts"),
  },
  loader: {
    ".ts": "ts",
  },
  banner: {
    js: "// Generated by go/internal/features/extensions/runtime/js — do not edit.",
  },
});

for (const warning of result.warnings) console.warn(warning.text);

const [output] = result.outputFiles;
writeFileSync(outFile, output.text);
const { size } = statSync(outFile);
console.log(`RaycastRuntime.generated.js — ${(size / 1024).toFixed(1)} KB${dev ? " (dev)" : ""}`);
